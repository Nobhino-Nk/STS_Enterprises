/* =========================================================
   PRODUCT HELPERS
   ========================================================= */


/**
 * Get one product by ID.
 *
 * Example:
 * getProductById("product-01")
 */
function getProductById(id) {

    return products.find(product => product.id === id);

}


/**
 * Get products belonging to a category.
 *
 * Example:
 * getProductsByCategory("acrylic")
 */
function getProductsByCategory(category) {

    return products.filter(product => product.category === category);

}


/**
 * Get all LED acrylic products.
 */
function getAcrylicProducts() {

    return getProductsByCategory("acrylic");

}


/**
 * Get all MDF products.
 */
function getMdfProducts() {

    return getProductsByCategory("mdf");

}


/**
 * Get all customisable products.
 */
function getCustomisableProducts() {

    return getProductsByCategory("custom");

}


/**
 * Get only products that are customisable.
 */
function getCustomisableProductsOnly() {

    return products.filter(product => product.customisable === true);

}


/**
 * Find a product by part of its name.
 *
 * Example:
 * getProductByName("Ganesh")
 */
function getProductByName(name) {

    const searchName = name.toLowerCase().trim();

    return products.find(product =>
        product.name.toLowerCase().includes(searchName)
    );

}


